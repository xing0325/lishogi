// Generates public/piece-css-taikyoku/kanji.css: taikyokudraft pieces drawn as a pentagon with the
// kanji name (vertical), promoted pieces in red, opponent pieces upside down.
// Run after building shogiops: node bin/taikyoku-piece-css.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { TAIKYOKU_ROLES, taikyokuKindOfRole, isPromotedTaikyokuRole } from '../ui/misc/node_modules/shogiops/dist/variant/taikyoku.js';

const pentagon = rot => {
  const g = rot ? ' transform="rotate(180 50 50)"' : '';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><polygon${g} points="50,5 82,17 91,95 9,95 18,17" fill="#f3d9a4" stroke="#7a5a2e" stroke-width="3" stroke-linejoin="round"/></svg>`;
  return `url('data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}')`;
};
const V = '.v-taikyokudraft';
const flipped = `${V} .sg-wrap.orientation-sente piece.gote, ${V} .sg-wrap.orientation-gote piece.sente`;
const out = [
  '/* Generated by bin/taikyoku-piece-css.mjs - do not edit */',
  `${V} piece { background-image: ${pentagon(false)}; background-size: 88% 92%; background-position: center; background-repeat: no-repeat; container-type: size; }`,
  `${flipped} { background-image: ${pentagon(true)}; }`,
  `${V} piece::after { position: absolute; inset: 0; display: flex; align-items: center; justify-content: center; writing-mode: vertical-rl; text-orientation: upright; letter-spacing: -0.06em; line-height: 1; color: #1b1208; font-family: "Noto Serif CJK JP", "Noto Serif CJK SC", "Hiragino Mincho ProN", "Yu Mincho", serif; font-weight: 700; font-size: 34cqh; padding-top: 6cqh; pointer-events: none; }`,
  `${flipped.split(', ').map(s => s + '::after').join(', ')} { transform: rotate(180deg); padding-top: 0; padding-bottom: 6cqh; }`,
  `${V} piece[class*="tkp-"]::after { color: #b3140f; }`,
];
for (const role of TAIKYOKU_ROLES) {
  const kanji = taikyokuKindOfRole(role)?.kanji ?? '?';
  const n = [...kanji].length;
  const size = n <= 1 ? 52 : n === 2 ? 36 : n === 3 ? 27 : 21;
  out.push(`${V} piece.${role}::after { content: "${kanji}";${size !== 34 ? ` font-size: ${size}cqh;` : ''} }`);
}
mkdirSync(new URL('../public/piece-css-taikyoku/', import.meta.url), { recursive: true });
writeFileSync(new URL('../public/piece-css-taikyoku/kanji.css', import.meta.url), out.join('\n') + '\n');
console.log(`${TAIKYOKU_ROLES.length} roles, ${TAIKYOKU_ROLES.filter(isPromotedTaikyokuRole).length} promoted`);
